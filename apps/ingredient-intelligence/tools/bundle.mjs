// Builds an inline <script> block (window.ClayII) from the module, and injects it into a Clay html file.
// usage: node bundle.mjs <clay.html>   (replaces text between the II markers, or inserts before the main <script>)
import fs from "node:fs"; import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const rd = f => fs.readFileSync(path.join(root, f), "utf8");
const strip = s => s.replace(/^export function /gm, "function ").replace(/^export const /gm, "const ").replace(/^import .*$/gm, "");
const j = f => JSON.stringify(JSON.parse(rd(f)));
const block = `<script id="ii-engine">/*II-BEGIN generated by apps/ingredient-intelligence/tools/bundle.mjs; do not edit here*/
(function(){
${strip(rd("src/engine.js"))}
${strip(rd("src/clay-adapter.js"))}
const DATA={ingredients:${j("data/ingredients.json")},rules:${j("data/pairing-rules.json")},sources:${j("data/sources.json")}};
window.ClayII={engine:createEngine(DATA),toEngineProduct:toEngineProduct,parseInci:parseInci,version:"0.1.1-clay"};
})();
/*II-END*/</script>
`;
const file = process.argv[2]; let h = fs.readFileSync(file, "utf8");
const re = /<script id="ii-engine">[\s\S]*?\/\*II-END\*\/<\/script>\n?/;
if (re.test(h)) h = h.replace(re, () => block);
else { const i = h.indexOf("<script>\nconst ICONS"); if (i < 0) throw new Error("anchor not found"); h = h.slice(0, i) + block + h.slice(i); }
fs.writeFileSync(file, h); console.log("bundled", block.length, "bytes into", file);
